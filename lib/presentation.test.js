test('authorizeUrl accepts only exact provider HTTPS authorize endpoints',()=>{
  const g='https://accounts.google.com/o/oauth2/v2/auth', m='https://evil.example/oauth2/v2.0/authorize', q='?state=s&code_challenge=c&code_challenge_method=S256';
  assert.equal(authorizeUrl(g+q,'Sheets'),g+q);
  for (const [u,p] of [[g+q,'Outlook'],[m+q,'Sheets'],[m+q,'Outlook'],[g+q,'Gmail'],['http://accounts.google.com/o/oauth2/v2/auth'+q,'Sheets'],['https://accounts.google.com:444/o/oauth2/v2/auth'+q,'Sheets'],['https://x@accounts.google.com/o/oauth2/v2/auth'+q,'Sheets'],['https://accounts.google.com.evil.example/o/oauth2/v2/auth'+q,'Sheets'],[g+'/x'+q,'Sheets'],[g+q+'#x','Sheets'],[g+'?state=s','Sheets'],['javascript:alert(1)','Sheets'],[undefined,'Sheets'],['/api/auth/connect','Sheets']]) assert.equal(authorizeUrl(u,p),null,String(u));
});
